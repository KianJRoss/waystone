import json
import tempfile
import unittest
from pathlib import Path

from native_services.skyrim_load_order import SkyrimLoadOrderSorter, SkyrimPlugin
from native_services.satisfactory_resolver import SatisfactoryPluginResolver, UPluginDependency, UPluginManifest
from native_services.rdr2_lml_stager import Rdr2LmlStager, LmlFileMapping


class TestGameModInfrastructureDeep(unittest.TestCase):
    def test_skyrim_load_order_topological_sort(self):
        sample_plugins = [
            SkyrimPlugin(name="Alternate Start - Live Another Life.esp", masters=["Skyrim.esm", "Update.esm"]),
            SkyrimPlugin(name="Update.esm"),
            SkyrimPlugin(name="Skyrim.esm"),
            SkyrimPlugin(name="Dragonborn.esm", masters=["Skyrim.esm"]),
            SkyrimPlugin(name="Unofficial Skyrim Special Edition Patch.esp", masters=["Skyrim.esm", "Update.esm"]),
            SkyrimPlugin(name="SkyUI_SE.esp"),
            SkyrimPlugin(name="Dawnguard.esm", masters=["Skyrim.esm"]),
            SkyrimPlugin(name="HearthFires.esm", masters=["Skyrim.esm"]),
        ]

        sorter = SkyrimLoadOrderSorter()
        sorted_plugins = sorter.sort_plugins(sample_plugins)
        sorted_names = [p.name.lower() for p in sorted_plugins]

        # Official masters must be strictly first in correct canonical order
        self.assertEqual(sorted_names[0], "skyrim.esm")
        self.assertEqual(sorted_names[1], "update.esm")
        self.assertEqual(sorted_names[2], "dawnguard.esm")
        self.assertEqual(sorted_names[3], "hearthfires.esm")
        self.assertEqual(sorted_names[4], "dragonborn.esm")

        # USSEP must precede general mods
        ussep_idx = sorted_names.index("unofficial skyrim special edition patch.esp")
        alt_start_idx = sorted_names.index("alternate start - live another life.esp")
        self.assertLess(ussep_idx, alt_start_idx)

    def test_skyrim_plugins_txt_parsing_and_serialization(self):
        raw_txt = (
            "# This file is generated by Waystone\n"
            "*Skyrim.esm\n"
            "*Update.esm\n"
            "Dawnguard.esm\n"
            "*SkyUI_SE.esp\n"
        )
        plugins = SkyrimLoadOrderSorter.parse_plugins_txt(raw_txt)
        self.assertEqual(len(plugins), 4)
        self.assertTrue(plugins[0].enabled)
        self.assertEqual(plugins[0].name, "Skyrim.esm")
        self.assertFalse(plugins[2].enabled)
        self.assertEqual(plugins[2].name, "Dawnguard.esm")

        serialized = SkyrimLoadOrderSorter.serialize_plugins_txt(plugins)
        self.assertIn("*Skyrim.esm", serialized)
        self.assertIn("Dawnguard.esm", serialized)
        self.assertNotIn("*Dawnguard.esm", serialized)

    def test_satisfactory_dependency_resolution(self):
        with tempfile.TemporaryDirectory() as tmp_dir:
            mods_path = Path(tmp_dir)

            # Create SML
            sml_dir = mods_path / "SML"
            sml_dir.mkdir()
            (sml_dir / "SML.uplugin").write_text(json.dumps({
                "SemVersion": "3.8.2",
                "FriendlyName": "Satisfactory Mod Loader",
                "Description": "Core loader",
                "Plugins": []
            }))

            # Create RefinedPower depending on SML
            rp_dir = mods_path / "RefinedPower"
            rp_dir.mkdir()
            (rp_dir / "RefinedPower.uplugin").write_text(json.dumps({
                "SemVersion": "3.3.0",
                "FriendlyName": "Refined Power",
                "Plugins": [
                    {"Name": "SML", "SemVersion": ">=3.8.0", "Enabled": True}
                ]
            }))

            # Create ModularLoaders depending on RefinedPower and SML
            ml_dir = mods_path / "ModularLoaders"
            ml_dir.mkdir()
            (ml_dir / "ModularLoaders.uplugin").write_text(json.dumps({
                "SemVersion": "1.0.5",
                "FriendlyName": "Modular Loaders",
                "Plugins": [
                    {"Name": "RefinedPower", "SemVersion": ">=3.0.0", "Enabled": True},
                    {"Name": "SML", "SemVersion": ">=3.8.0", "Enabled": True}
                ]
            }))

            resolver = SatisfactoryPluginResolver(mods_path)
            result = resolver.resolve()
            self.assertTrue(result.valid)
            self.assertEqual(len(result.missing_dependencies), 0)
            self.assertEqual(len(result.version_conflicts), 0)

            # SML must be loaded before RefinedPower and ModularLoaders
            sml_idx = result.load_order.index("SML")
            rp_idx = result.load_order.index("RefinedPower")
            ml_idx = result.load_order.index("ModularLoaders")
            self.assertLess(sml_idx, rp_idx)
            self.assertLess(rp_idx, ml_idx)

    def test_satisfactory_missing_and_version_conflict_detection(self):
        with tempfile.TemporaryDirectory() as tmp_dir:
            mods_path = Path(tmp_dir)

            # SML 3.8.2
            sml_dir = mods_path / "SML"
            sml_dir.mkdir()
            (sml_dir / "SML.uplugin").write_text(json.dumps({
                "SemVersion": "3.8.2",
                "Plugins": []
            }))

            # BrokenMod requiring missing lib and newer SML
            b_dir = mods_path / "BrokenMod"
            b_dir.mkdir()
            (b_dir / "BrokenMod.uplugin").write_text(json.dumps({
                "SemVersion": "1.0.0",
                "Plugins": [
                    {"Name": "MissingLib", "SemVersion": ">=1.0.0", "Enabled": True},
                    {"Name": "SML", "SemVersion": ">=4.0.0", "Enabled": True}
                ]
            }))

            resolver = SatisfactoryPluginResolver(mods_path)
            result = resolver.resolve()
            self.assertFalse(result.valid)
            self.assertIn("BrokenMod", result.missing_dependencies)
            self.assertTrue(len(result.version_conflicts) > 0)

    def test_rdr2_lml_xml_parsing(self):
        xml_content = """<?xml version="1.0" encoding="utf-8"?>
<Package>
    <Name>WhyEm DLC Redux</Name>
    <Author>WhyEm</Author>
    <Version>1.2.5</Version>
    <Description>Extensive clothing and equipment overhaul</Description>
    <Files>
        <File from="stream/player_zero.ydr" to="stream/player_zero.ydr"/>
        <File from="scripts/WhyEm.asi" to="WhyEm.asi"/>
        <File from="replace/peddamage.meta" to="replace/peddamage.meta"/>
    </Files>
</Package>
"""
        info = Rdr2LmlStager.parse_install_xml(xml_content)
        self.assertIsNotNone(info)
        self.assertEqual(info.name, "WhyEm DLC Redux")
        self.assertEqual(info.author, "WhyEm")
        self.assertEqual(len(info.mappings), 3)

        stream_map = [m for m in info.mappings if m.is_stream]
        root_map = [m for m in info.mappings if m.is_root]
        self.assertEqual(len(stream_map), 1)
        self.assertEqual(len(root_map), 2)

    def test_rdr2_routing_and_proton_env(self):
        file_list = [
            "install.xml",
            "stream/hats.ydr",
            "ScriptHookRDR2.dll",
            "dinput8.dll",
            "ScriptHookRDR2.ini",
            "lml_mod.ini",
            "subfolder/textures.ytd",
        ]
        routes = Rdr2LmlStager.classify_rdr2_files(file_list)
        self.assertEqual(routes["stream/hats.ydr"], "lml/stream/hats.ydr")
        self.assertEqual(routes["subfolder/textures.ytd"], "lml/stream/textures.ytd")
        self.assertEqual(routes["ScriptHookRDR2.ini"], "ScriptHookRDR2.ini")
        self.assertEqual(routes["lml_mod.ini"], "lml/lml_mod.ini")

        proton_env = Rdr2LmlStager.get_proton_environment()
        self.assertIn("WINEDLLOVERRIDES", proton_env)
        self.assertIn("dinput8=n,b", proton_env["WINEDLLOVERRIDES"])
        self.assertIn("vfs=n,b", proton_env["WINEDLLOVERRIDES"])


if __name__ == "__main__":
    unittest.main()
