using System.Text;
using UnifiedController.Core;

namespace UnifiedController.Linux.App.Services;

public static class HotkeyBindingService
{
    public const string IncludeLine = "source = ~/.config/hypr/unified-controller-hotkeys.conf";
    public static IReadOnlyList<(string Key, string Action)> Defaults { get; } =
    [
        ("F10", RuntimeActions.OpenControlCenter), ("F12", RuntimeActions.KeyboardControllerMode),
        ("F11", RuntimeActions.MouseAimMode), ("F9", RuntimeActions.DesktopMode),
        ("F8", RuntimeActions.CancelMacros), ("F1", RuntimeActions.FishingHelperToggle)
    ];

    public static string BuildHyprlandContent()
    {
        var text = new StringBuilder("# Generated by Unified Controller. Add this file with:\n# ").AppendLine(IncludeLine);
        foreach (var (key, action) in Defaults)
            text.Append("bind = CTRL ALT, ").Append(key).Append(", exec, unified-controller --action \"").Append(action).AppendLine("\"");
        return text.ToString();
    }

    public static string Install(string? home = null)
    {
        home ??= Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
        if (string.IsNullOrWhiteSpace(home)) throw new InvalidOperationException("The user home directory could not be determined.");
        var path = Path.Combine(home, ".config", "hypr", "unified-controller-hotkeys.conf");
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, BuildHyprlandContent(), new UTF8Encoding(false));
        return path;
    }
}
